METHODS = ("InherNet", "Weight SVD", "Activation-aware", "Hetero")
ACTIVE_TOLERANCE = 1e-7


def validate_data() -> None:
    assert all(tuple(dataset["methods"]) == METHODS for dataset in ROUTER_DATA.values())
    for dataset in ROUTER_DATA.values():
        count = len(dataset["methods"]["InherNet"])
        assert all(len(values) == count for values in dataset["methods"].values())
        assert all(value < ACTIVE_TOLERANCE for method in METHODS[:-1]
                   for value in dataset["methods"][method])
        assert all(value >= ACTIVE_TOLERANCE for value in dataset["methods"]["Hetero"])


def plot(output: Path) -> None:
    validate_data()
    plt = get_pyplot("single")
    from matplotlib.lines import Line2D

    fig, ax = plt.subplots(figsize=(7.1, 4.25))
    starts = {"oxford_pets": 0.0, "cifar100": 5.0}
    ticks = []
    labels = []
    for dataset_name, dataset in ROUTER_DATA.items():
        color = dataset["color"]
        for method_index, method in enumerate(METHODS):
            center = starts[dataset_name] + method_index
            values = dataset["methods"][method]
            count = len(values)
            offsets = [0.28 * (index / (count - 1) - 0.5) for index in range(count)]
            ax.scatter(
                [center + offset for offset in offsets],
                values,
                s=18,
                color=color,
                alpha=0.6,
                linewidth=0,
                zorder=3,
            )
            median = statistics.median(values)
            ax.plot([center - 0.18, center + 0.18], [median, median],
                    color="#111827", linewidth=2.1, zorder=4)
            active = sum(value >= ACTIVE_TOLERANCE for value in values)
            count_y = 1.55e-7 if active == 0 else max(values) * 1.6
            ax.text(center, count_y, f"{active}/{count}", ha="center", va="bottom", fontsize=7.8)
            ticks.append(center)
            labels.append(method.replace("Activation-aware", "Activation\naware"))

    ax.axhline(ACTIVE_TOLERANCE, color="#6B7280", linestyle="--", linewidth=1.1, zorder=1)
    ax.set_yscale("log")
    ax.set_ylim(1e-10, 4e-2)
    ax.set_xlim(-0.55, 8.55)
    ax.set_xticks(ticks, labels, fontsize=7.8)
    ax.get_xticklabels()[3].set_fontweight("bold")
    ax.get_xticklabels()[7].set_fontweight("bold")
    ax.set_ylabel("Per-router teacher-KL gate-gradient norm")
    ax.set_title("Router activity across inheritance controls", pad=31)
    ax.grid(False)
    legend_handles = [
        Line2D([], [], color="#0072B2", marker="o", linestyle="None", markersize=6,
               label="Oxford Pets"),
        Line2D([], [], color="#D55E00", marker="o", linestyle="None", markersize=6,
               label="CIFAR-100"),
        Line2D([], [], color="#111827", linewidth=2.1, label="Median"),
        Line2D([], [], color="#6B7280", linestyle="--", linewidth=1.1,
               label=r"Activity threshold ($10^{-7}$)"),
    ]
    ax.legend(
        handles=legend_handles,
        loc="upper center",
        bbox_to_anchor=(0.5, 1.12),
        ncol=4,
        columnspacing=1.25,
        handletextpad=0.5,
        fontsize=8.5,
    )
    fig.tight_layout()
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=300, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=PROJECT_DIR / "figures" / "prestudy_router_activity.png",
    )
    args = parser.parse_args()
    plot(args.output)
    print(f"Wrote 300-DPI figure: {args.output}")


if __name__ == "__main__":
    main()
